#!/usr/bin/env bash
# Writes db/migrations/0002_mastra_schema.sql: the tables that storage.init() of
# PostgresStore makes in schema mastra. It starts its own throwaway local Postgres,
# runs init once, dumps the schema, and stops the server. It never touches a remote database.
# Run it again after each @mastra/pg upgrade. tests/store/migrations.test.ts fails when the file is out of date.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/db/migrations/0002_mastra_schema.sql"
export HARNESS_TEST_DB_DIR="${TMPDIR:-/tmp}/product-eval-harness-mastra-dump"
export MASTRA_TELEMETRY_DISABLED=1
trap '"$ROOT/scripts/test-db.sh" stop' EXIT

URL="$("$ROOT/scripts/test-db.sh" start | sed 's/^HARNESS_TEST_DATABASE_URL=//')"
PORT="$(cat "$HARNESS_TEST_DB_DIR/port")"
# Postgres 18 from Homebrew when present, else the pg_dump on PATH.
if [ -z "${PG_BIN:-}" ]; then
  if [ -x /opt/homebrew/opt/postgresql@18/bin/pg_dump ]; then PG_BIN=/opt/homebrew/opt/postgresql@18/bin
  else PG_BIN="$(dirname "$(command -v pg_dump)")"; fi
fi

(cd "$ROOT" && npx tsx scripts/mastra-init.ts "$URL")

PG_VERSION="$("$PG_BIN/pg_dump" --version)"
MASTRA_PG="$(node -p "require('$ROOT/node_modules/@mastra/pg/package.json').version")"
{
  echo "-- The Mastra storage tables, in schema mastra."
  echo "-- Generated by scripts/dump-mastra-schema.sh. Do not edit by hand."
  echo "-- Source: storage.init() of @mastra/pg $MASTRA_PG, dumped with $PG_VERSION"
  echo "-- (--schema-only --schema=mastra --no-owner --no-privileges)."
  echo "-- The script removes the session SET lines and the psql \\restrict lines of pg_dump,"
  echo "-- so that the file is plain SQL that leaves the session settings as they were."
  echo
  # pg_dump 18 adds \restrict and \unrestrict lines with a random key: psql commands, not SQL.
  # Its SET lines change the session (search_path to ''), which would leak into later files.
  "$PG_BIN/pg_dump" --schema-only --schema=mastra --no-owner --no-privileges \
      -h 127.0.0.1 -p "$PORT" -U postgres postgres \
    | grep -v -E '^\\(restrict|unrestrict) ' \
    | grep -v -E '^SET [a-z_]+ = ' \
    | grep -v -E "^SELECT pg_catalog\.set_config\('search_path'" \
    | cat -s
} > "$OUT"
echo "Wrote $OUT"
